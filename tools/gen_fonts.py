#!/usr/bin/env python3
"""Rasterises souldew's UI fonts into 4-bit alpha bitmap fonts (common/fonts_data.cpp).

The fonts (assets/fonts, SIL Open Font License): Pixelify Sans and IBM Plex Sans (the variable latin
subsets the desktop app ships) and Silkscreen. Needs Pillow (with FreeType + Raqm-free basic layout).
The generated file is committed, so building souldew-3ds does not need Python.

    python3 tools/gen_fonts.py [--preview out.png]
"""
import os, sys
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FD = os.path.join(ROOT, 'assets', 'fonts')

# (id, file, px size, weight or None, antialias)
FONTS = [
    ('FONT_DISPLAY', 'PixelifySans-VF-latin.ttf', 22, 600, False),  # run names, big headings
    ('FONT_HEAD', 'PixelifySans-VF-latin.ttf', 15, 600, True),      # card titles, nicknames
    ('FONT_LABEL', 'Silkscreen-Regular.ttf', 8, None, False),       # small caps labels, chips
    ('FONT_NUM', 'Silkscreen-Regular.ttf', 16, None, False),        # stat tiles, level cap
    ('FONT_BODY', 'IBMPlexSans-VF-latin.ttf', 12, 500, True),       # body text
    ('FONT_BODY_B', 'IBMPlexSans-VF-latin.ttf', 12, 600, True),     # buttons, emphasis
    ('FONT_SMALL', 'IBMPlexSans-VF-latin.ttf', 10, 500, True),      # secondary lines
]

CHARS = [c for c in range(0x20, 0x7F)] + [c for c in range(0xA0, 0x100)] + \
        [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x201E, 0x2026, 0x2022, 0x2212, 0x00D7]


def load(file, size, weight):
    f = ImageFont.truetype(os.path.join(FD, file), size)
    if weight is not None:
        try:
            f.set_variation_by_axes([weight])
        except Exception as e:  # pragma: no cover
            print('variation failed', file, e, file=sys.stderr)
    return f


def has_glyph(font, cp):
    from fontTools.ttLib import TTFont
    return True


def build():
    from fontTools.ttLib import TTFont
    out = []
    previews = []
    out.append('// Generated by tools/gen_fonts.py – do not edit. Fonts: SIL Open Font License (assets/fonts).')
    out.append('#include "fonts.h"')
    out.append('namespace sd {')
    for fid, file, size, weight, aa in FONTS:
        cmap = TTFont(os.path.join(FD, file)).getBestCmap()
        font = load(file, size, weight)
        ascent, descent = font.getmetrics()
        glyphs = []
        data = bytearray()
        for cp in CHARS:
            if cp not in cmap:
                continue
            ch = chr(cp)
            adv = int(round(font.getlength(ch)))
            bbox = font.getbbox(ch, anchor='ls')  # relative to baseline origin
            if bbox is None or bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
                glyphs.append((cp, 0, 0, 0, 0, adv, len(data)))
                continue
            x0, y0, x1, y1 = bbox
            w, h = x1 - x0, y1 - y0
            img = Image.new('L', (w + 4, h + 4), 0)
            d = ImageDraw.Draw(img)
            d.fontmode = 'L' if aa else '1'
            d.text((2 - x0, 2 - y0), ch, font=font, fill=255, anchor='ls')
            bb = img.getbbox()
            if not bb:
                glyphs.append((cp, 0, 0, 0, 0, adv, len(data)))
                continue
            img = img.crop(bb)
            gx = bb[0] - 2 + x0
            gy = bb[1] - 2 + y0  # top relative to baseline (negative = above)
            w, h = img.size
            px = list(img.get_flattened_data()) if hasattr(img, 'get_flattened_data') else list(img.getdata())
            off = len(data)
            # 4-bit alpha, two pixels per byte, rows padded to whole bytes
            for row in range(h):
                r = px[row * w:(row + 1) * w]
                for i in range(0, w, 2):
                    a = (r[i] + 8) // 17
                    b = (r[i + 1] + 8) // 17 if i + 1 < w else 0
                    data.append((a << 4) | b)
            glyphs.append((cp, gx, gy, w, h, adv, off))
        name = fid.lower()
        out.append(f'static const unsigned char {name}_bits[] = {{')
        for i in range(0, len(data), 24):
            out.append('  ' + ','.join(str(b) for b in data[i:i + 24]) + ',')
        out.append('};')
        out.append(f'static const Glyph {name}_glyphs[] = {{')
        for g in glyphs:
            out.append('  {%d,%d,%d,%d,%d,%d,%d},' % g)
        out.append('};')
        out.append(f'const Font {name} = {{ {ascent}, {descent}, {len(glyphs)}, {name}_glyphs, {name}_bits }};')
        previews.append((fid, font, aa))
    out.append('}  // namespace sd')
    with open(os.path.join(ROOT, 'common', 'fonts_data.cpp'), 'w') as fh:
        fh.write('\n'.join(out) + '\n')
    return previews


if __name__ == '__main__':
    p = build()
    if '--preview' in sys.argv:
        img = Image.new('RGB', (400, 30 * len(p)), (27, 26, 31))
        d = ImageDraw.Draw(img)
        for i, (fid, font, aa) in enumerate(p):
            d.fontmode = 'L' if aa else '1'
            d.text((4, 4 + i * 30), 'Kims Nuzlocke 0123456789 äöüß ♀♂', font=font, fill=(235, 230, 218))
        img.save(sys.argv[sys.argv.index('--preview') + 1])
    print('ok')
